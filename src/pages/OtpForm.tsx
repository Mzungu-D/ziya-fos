import {
  useEffect,
  useState,
} from "react";

import {
  Link,
  useLocation,
  useNavigate,
} from "react-router-dom";

import {
  ArrowLeft,
  ArrowRight,
  Mail,
  Phone,
  RotateCcw,
  ShieldCheck,
} from "lucide-react";

import { API_URL } from "../lib/api";
import {
  storeAuthenticatedSession,
} from "../lib/auth";

import ziyaLogo from "../assets/zayi.jpg";
import heroImage from "../assets/ziya-cinematic-hero.webp";

type OtpChannel =
  | "EMAIL"
  | "PHONE";

interface OtpLocationState {
  email?: string;
  phoneNumber?: string;

  otpChannel?: OtpChannel;

  destination?: string;

  sessionType?:
    | "PLATFORM"
    | "TENANT"
    | string;

  rememberMe?: boolean;

  /*
   * Used only during the current browser
   * navigation so the login endpoint can
   * be called again if the user requests
   * another OTP.
   *
   * This value is NOT written to
   * localStorage or sessionStorage.
   */
  password?: string;
}

interface VerifyResponse {
  success?: boolean;

  message?: string;

  token?: string;

  sessionType?:
    | "PLATFORM"
    | "TENANT";

  verificationChannel?:
    OtpChannel;

  user?: {
    id?: string;

    name?: string;

    email?: string;

    phoneNumber?: string | null;

    phoneVerifiedAt?: string | null;

    platformRole?: string | null;

    organizationId?: string;

    organizationRole?: string;

    permissions?: string[];
  };

  organization?: {
    id?: string;

    name?: string;

    slug?: string;

    logoUrl?: string | null;

    country?: string;

    currency?: string;
  };

  organizations?: unknown[];
}

interface LoginResponse {
  success?: boolean;

  requiresOtp?: boolean;

  message?: string;

  code?: string;

  retryAfterSeconds?: number;

  verification?: {
    channel?: OtpChannel;

    destination?: string;

    sessionType?:
      | "PLATFORM"
      | "TENANT";
  };
}

const INITIAL_COOLDOWN_SECONDS = 60;

export default function OtpForm() {
  const navigate = useNavigate();

  const location = useLocation();

  const state =
    (location.state as
      | OtpLocationState
      | null) ?? {};

  const email =
    state.email?.trim() ?? "";

  const phoneNumber =
    state.phoneNumber?.trim() ?? "";

  const otpChannel: OtpChannel =
    state.otpChannel === "PHONE"
      ? "PHONE"
      : "EMAIL";

  const rememberMe =
    Boolean(state.rememberMe);

  const [destination, setDestination] =
    useState(
      state.destination ?? ""
    );

  const [otp, setOtp] =
    useState("");

  const [error, setError] =
    useState("");

  const [message, setMessage] =
    useState(
      "Verification code sent successfully."
    );

  const [verifying, setVerifying] =
    useState(false);

  const [resending, setResending] =
    useState(false);

  /*
   * The first OTP was generated by
   * the login page, so the resend
   * countdown begins immediately.
   */
  const [
    cooldownSeconds,
    setCooldownSeconds,
  ] = useState(
    INITIAL_COOLDOWN_SECONDS
  );

  /* =====================================================
     IDENTIFIER VALIDATION
  ===================================================== */

  const hasValidIdentifier =
    otpChannel === "PHONE"
      ? Boolean(phoneNumber)
      : Boolean(email);

  /* =====================================================
     PROTECT DIRECT ACCESS TO /OTP
  ===================================================== */

  useEffect(() => {
    if (!hasValidIdentifier) {
      navigate("/login", {
        replace: true,
      });
    }
  }, [
    hasValidIdentifier,
    navigate,
  ]);

  /* =====================================================
     RESEND COUNTDOWN
  ===================================================== */

  useEffect(() => {
    if (cooldownSeconds <= 0) {
      return;
    }

    const timer =
      window.setTimeout(() => {
        setCooldownSeconds(
          (current) =>
            Math.max(
              0,
              current - 1
            )
        );
      }, 1000);

    return () => {
      window.clearTimeout(timer);
    };
  }, [cooldownSeconds]);

  /* =====================================================
     OTP INPUT
  ===================================================== */

  const handleOtpChange = (
    event: React.ChangeEvent<HTMLInputElement>
  ) => {
    const digitsOnly =
      event.target.value
        .replace(/\D/g, "")
        .slice(0, 6);

    setOtp(digitsOnly);

    setError("");
  };

  /* =====================================================
     VERIFY OTP
  ===================================================== */

  const handleVerify = async (
    event: React.FormEvent<HTMLFormElement>
  ) => {
    event.preventDefault();

    if (!/^\d{6}$/.test(otp)) {
      setError(
        "Enter the complete 6-digit verification code."
      );

      return;
    }

    if (!hasValidIdentifier) {
      setError(
        "Your verification session has expired. Please sign in again."
      );

      return;
    }

    try {
      setVerifying(true);

      setError("");

      setMessage("");

      const response = await fetch(
        `${API_URL}/api/auth/verify-otp`,
        {
          method: "POST",

          headers: {
            "Content-Type":
              "application/json",
          },
          credentials: "include",

          body: JSON.stringify({
            email:
              otpChannel === "EMAIL"
                ? email
                : undefined,

            phoneNumber:
              otpChannel === "PHONE"
                ? phoneNumber
                : undefined,

            otp,

            otpChannel,

            rememberMe,
            trustDevice: true,
          }),
        }
      );

      const data: VerifyResponse =
        await response.json();

      if (
        !response.ok ||
        !data.success
      ) {
        setError(
          data.message ||
            "Verification failed. Please try again."
        );

        return;
      }

      if (!data.token) {
        setError(
          "Authentication succeeded but no access token was returned."
        );

        return;
      }

      if (!data.sessionType) {
        setError(
          "Authentication succeeded but no session type was returned."
        );

        return;
      }

      if (!data.user) {
        setError(
          "Authentication succeeded but no user session was returned."
        );

        return;
      }

      /*
       * The backend returns the user's
       * organization membership permissions
       * here.
       *
       * Those permissions are stored by the
       * centralized auth helper and are then
       * consumed by:
       *
       * - Sidebar
       * - RequirePermission
       * - TenantLanding
       * - OrganizationSwitcher
       */
      storeAuthenticatedSession(
        {
          token: data.token,

          sessionType:
            data.sessionType,

          user: {
            ...data.user,

            permissions:
              Array.isArray(
                data.user.permissions
              )
                ? data.user.permissions
                : [],
          },

          organization:
            data.organization,
        },
        rememberMe
      );

      setOtp("");

      /*
       * Authentication is now complete.
       *
       * The backend explicitly identifies
       * which security workspace this session
       * belongs to:
       *
       * PLATFORM
       *   -> Platform Administration
       *
       * TENANT
       *   -> Organization Financial Workspace
       *
       * We deliberately use sessionType rather
       * than platformRole here because sessionType
       * is the authoritative security boundary
       * for the authenticated session.
       */
      const landingPage =
        data.sessionType === "PLATFORM"
          ? "/platform"
          : "/dashboard";

      navigate(landingPage, {
        replace: true,
      });
    } catch (err) {
      console.error(
        "[OTP] Verification failed:",
        err
      );

      setError(
        err instanceof Error
          ? err.message
          : "Unable to verify the code. Please try again."
      );
    } finally {
      setVerifying(false);
    }
  };

  /* =====================================================
     RESEND OTP
  ===================================================== */

  const handleResend = async () => {
    /*
     * Frontend protection.
     *
     * Backend independently enforces
     * the cooldown as well.
     */
    if (
      cooldownSeconds > 0 ||
      resending ||
      verifying
    ) {
      return;
    }

    if (!state.password) {
      setError(
        "Your sign-in session must be restarted before another code can be requested."
      );

      return;
    }

    if (
      otpChannel === "PHONE" &&
      !phoneNumber
    ) {
      setError(
        "Your phone verification session has expired. Please sign in again."
      );

      return;
    }

    if (
      otpChannel === "EMAIL" &&
      !email
    ) {
      setError(
        "Your email verification session has expired. Please sign in again."
      );

      return;
    }

    try {
      setResending(true);

      setError("");

      setMessage("");

      const payload: {
        email?: string;

        password: string;

        otpChannel: OtpChannel;

        phoneNumber?: string;
      } = {
        password:
          state.password,

        otpChannel,
      };

      if (otpChannel === "EMAIL") {
        payload.email = email;
      }

      if (otpChannel === "PHONE") {
        payload.phoneNumber =
          phoneNumber;
      }

      const response = await fetch(
        `${API_URL}/api/auth/login`,
        {
          method: "POST",

          headers: {
            "Content-Type":
              "application/json",
          },
          credentials: "include",

          body: JSON.stringify(payload),
        }
      );

      const data: LoginResponse =
        await response.json();

      /*
       * Backend cooldown is authoritative.
       */
      if (
        response.status === 429 &&
        data.code ===
          "OTP_COOLDOWN"
      ) {
        const retryAfter =
          typeof data.retryAfterSeconds ===
          "number"
            ? Math.max(
                1,
                Math.ceil(
                  data.retryAfterSeconds
                )
              )
            : INITIAL_COOLDOWN_SECONDS;

        setCooldownSeconds(
          retryAfter
        );

        setError(
          data.message ||
            `Please wait ${retryAfter} seconds before requesting another code.`
        );

        return;
      }

      if (!response.ok) {
        setError(
          data.message ||
            "Unable to send another verification code."
        );

        return;
      }

      if (
        !data.success ||
        !data.requiresOtp
      ) {
        setError(
          "The server did not create a new verification challenge."
        );

        return;
      }

      if (
        data.verification
          ?.destination
      ) {
        setDestination(
          data.verification
            .destination
        );
      }

      setOtp("");

      setCooldownSeconds(
        INITIAL_COOLDOWN_SECONDS
      );

      setMessage(
        otpChannel === "PHONE"
          ? "A new verification code was sent to your phone."
          : "A new verification code was sent to your email."
      );
    } catch (err) {
      console.error(
        "[OTP] Resend failed:",
        err
      );

      setError(
        "Unable to send another code. Please try again."
      );
    } finally {
      setResending(false);
    }
  };

  /* =====================================================
     WAIT FOR REDIRECT WHEN DIRECT ACCESS IS INVALID
  ===================================================== */

  if (!hasValidIdentifier) {
    return null;
  }

  const isPhone =
    otpChannel === "PHONE";

  const resendDisabled =
    cooldownSeconds > 0 ||
    resending ||
    verifying;

  /* =====================================================
     UI
  ===================================================== */

  return (
    <div className="grid min-h-screen bg-[#081019] text-white lg:grid-cols-[1.05fr_0.95fr]">
      {/* ===================================================
          VISUAL SIDE
      =================================================== */}

      <section className="relative hidden overflow-hidden lg:block">
        <img
          src={heroImage}
          alt=""
          className="absolute inset-0 h-full w-full object-cover"
        />

        <div className="absolute inset-0 bg-black/30" />

        <div className="absolute inset-0 bg-gradient-to-t from-black/65 via-transparent to-black/20" />

        <Link
          to="/"
          className="absolute left-10 top-9 z-10 flex items-center gap-3"
        >
          <img
            src={ziyaLogo}
            alt="Ziya"
            className="h-11 w-11 rounded-full object-cover"
          />

          <span className="font-semibold tracking-[0.17em]">
            ZIYA FOS
          </span>
        </Link>

        <div className="absolute bottom-12 left-10 right-10 z-10">
          <h2 className="max-w-xl text-5xl font-medium leading-[1.02] tracking-[-0.04em]">
            Secure access.
            <br />
            Verified every time.
          </h2>

          <p className="mt-5 max-w-lg leading-7 text-white/70">
            Two-step verification protects
            access to your organization's
            financial workspace.
          </p>
        </div>
      </section>

      {/* ===================================================
          OTP SIDE
      =================================================== */}

      <section className="flex min-h-screen items-center justify-center px-6 py-12 md:px-12">
        <div className="w-full max-w-md">
          {/* Mobile logo */}

          <div className="mb-10 flex items-center justify-between lg:hidden">
            <Link
              to="/"
              className="flex items-center gap-3"
            >
              <img
                src={ziyaLogo}
                alt="Ziya"
                className="h-10 w-10 rounded-full object-cover"
              />

              <span className="font-semibold tracking-[0.15em]">
                ZIYA FOS
              </span>
            </Link>
          </div>

          {/* Back */}

          <button
            type="button"
            onClick={() =>
              navigate("/login", {
                replace: true,
              })
            }
            className="mb-10 hidden items-center gap-2 text-sm text-white/50 transition hover:text-white lg:inline-flex"
          >
            <ArrowLeft size={17} />
            Back to sign in
          </button>

          {/* Channel icon */}

          <div className="flex h-12 w-12 items-center justify-center rounded-2xl border border-[#e5b83b]/25 bg-[#e5b83b]/10 text-[#e5b83b]">
            {isPhone ? (
              <Phone size={22} />
            ) : (
              <Mail size={22} />
            )}
          </div>

          <p className="mt-7 text-sm font-semibold uppercase tracking-[0.22em] text-[#e5b83b]">
            Two-step verification
          </p>

          <h1 className="mt-4 text-4xl font-semibold tracking-[-0.04em]">
            Check your{" "}
            {isPhone
              ? "phone"
              : "email"}
            .
          </h1>

          <p className="mt-3 leading-7 text-white/50">
            Enter the 6-digit verification
            code sent to
          </p>

          <p className="mt-1 font-semibold text-white/80">
            {destination ||
              (isPhone
                ? "your registered phone number"
                : email)}
          </p>

          {/* =================================================
              OTP FORM
          ================================================= */}

          <form
            className="mt-9"
            onSubmit={handleVerify}
          >
            <label className="block">
              <span className="mb-2 block text-sm font-medium text-white/75">
                Verification code
              </span>

              <input
                type="text"
                inputMode="numeric"
                autoComplete="one-time-code"
                maxLength={6}
                value={otp}
                onChange={
                  handleOtpChange
                }
                autoFocus
                placeholder="000000"
                className="h-16 w-full rounded-2xl border border-white/10 bg-white/[0.04] px-5 text-center text-2xl font-semibold tracking-[0.45em] text-white outline-none transition placeholder:text-white/15 focus:border-white/30"
              />
            </label>

            {/* =================================================
                MESSAGE
            ================================================= */}

            {message && (
              <div className="mt-4 rounded-2xl border border-white/10 bg-white/[0.025] px-4 py-3 text-sm leading-6 text-white/50">
                {message}
              </div>
            )}

            {/* =================================================
                ERROR
            ================================================= */}

            {error && (
              <div className="mt-4 rounded-2xl border border-red-400/20 bg-red-400/10 px-4 py-3 text-sm leading-6 text-red-200">
                {error}
              </div>
            )}

            {/* =================================================
                VERIFY
            ================================================= */}

            <button
              type="submit"
              disabled={
                verifying ||
                resending ||
                otp.length !== 6
              }
              className="mt-7 flex h-14 w-full items-center justify-center gap-3 rounded-full bg-white font-semibold text-[#081019] transition hover:bg-white/90 disabled:cursor-not-allowed disabled:opacity-50"
            >
              {verifying
                ? "Verifying..."
                : "Verify and continue"}

              {!verifying && (
                <ArrowRight size={18} />
              )}
            </button>
          </form>

          {/* =================================================
              RESEND
          ================================================= */}

          <button
            type="button"
            disabled={
              resendDisabled
            }
            onClick={() =>
              void handleResend()
            }
            className="mt-5 flex w-full items-center justify-center gap-2 text-sm font-medium text-white/55 transition hover:text-white disabled:cursor-not-allowed disabled:text-white/25"
          >
            <RotateCcw size={16} />

            {resending
              ? "Sending another code..."
              : cooldownSeconds > 0
                ? `Send another code in ${cooldownSeconds}s`
                : "Didn't receive it? Send another code"}
          </button>

          {/* =================================================
              SECURITY INFORMATION
          ================================================= */}

          <div className="mt-8 flex gap-3 rounded-2xl border border-white/10 bg-white/[0.025] p-4">
            <ShieldCheck
              size={20}
              className="shrink-0 text-[#e5b83b]"
            />

            <p className="text-sm leading-6 text-white/45">
              Verification codes expire after
              10 minutes. This device will be
              trusted after successful verification.
              Never share your verification code
              with anyone.
            </p>
          </div>

          {/* =================================================
              CHANGE METHOD
          ================================================= */}

          <button
            type="button"
            onClick={() =>
              navigate("/login", {
                replace: true,
              })
            }
            className="mt-7 flex w-full items-center justify-center gap-2 text-sm text-white/40 transition hover:text-white"
          >
            <ArrowLeft size={16} />
            Use another verification method
          </button>
        </div>
      </section>
    </div>
  );
}