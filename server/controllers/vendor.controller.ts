import { Response } from "express";
import prisma from "../config/prisma";
import { AuthRequest } from "../middleware/auth.middleware";

const getParam = (
  value: string | string[] | undefined
): string => {
  if (Array.isArray(value)) return value[0] ?? "";
  return value ?? "";
};

const cleanOptionalString = (
  value: unknown
): string | null => {
  if (typeof value !== "string") return null;

  const cleaned = value.trim();
  return cleaned || null;
};

const getOrganizationId = (
  req: AuthRequest
): string | null => {
  const organizationId =
    req.user?.organizationId?.trim();

  return organizationId || null;
};

/**
 * Generate the next vendor code for one organization.
 *
 * Codes are generated by the server and are never accepted
 * from the client.
 */
const generateVendorCode = async (
  organizationId: string
): Promise<string> => {
  const year = new Date().getFullYear();
  const prefix = `VEN-${year}-`;

  const existing = await prisma.vendor.findMany({
    where: {
      organizationId,
      vendorCode: {
        startsWith: prefix,
      },
    },
    select: {
      vendorCode: true,
    },
    orderBy: {
      vendorCode: "desc",
    },
  });

  let highest = 0;

  for (const item of existing) {
    const match = item.vendorCode.match(
      new RegExp(`^VEN-${year}-(\\d+)$`)
    );

    if (match) {
      highest = Math.max(
        highest,
        Number(match[1])
      );
    }
  }

  return `${prefix}${String(highest + 1).padStart(3, "0")}`;
};

/* =========================================================
   CREATE
========================================================= */

export const createVendor = async (
  req: AuthRequest,
  res: Response
) => {
  try {
    const organizationId =
      getOrganizationId(req);

    if (!organizationId) {
      return res.status(401).json({
        success: false,
        message: "Organization context is required.",
      });
    }

    const {
      name,
      email,
      phoneNumber,
      address,
      taxNumber,
    } = req.body ?? {};

    if (
      typeof name !== "string" ||
      !name.trim()
    ) {
      return res.status(400).json({
        success: false,
        message: "Vendor name is required.",
      });
    }

    for (let attempt = 0; attempt < 5; attempt++) {
      try {
        const vendorCode =
          await generateVendorCode(
            organizationId
          );

        const vendor =
          await prisma.vendor.create({
            data: {
              organizationId,
              vendorCode,
              name: name.trim(),
              email:
                typeof email === "string" &&
                email.trim()
                  ? email.trim().toLowerCase()
                  : null,
              phoneNumber:
                cleanOptionalString(phoneNumber),
              address:
                cleanOptionalString(address),
              taxNumber:
                typeof taxNumber === "string" &&
                taxNumber.trim()
                  ? taxNumber.trim().toUpperCase()
                  : null,
              status: "ACTIVE",
            },
          });

        return res.status(201).json({
          success: true,
          message: "Vendor created successfully.",
          vendor,
        });
      } catch (error: any) {
        if (error?.code === "P2002") {
          continue;
        }

        throw error;
      }
    }

    return res.status(409).json({
      success: false,
      message:
        "Unable to generate a unique vendor code. Please try again.",
    });
  } catch (error) {
    console.error(
      "CREATE VENDOR ERROR:",
      error
    );

    return res.status(500).json({
      success: false,
      message: "Failed to create vendor.",
    });
  }
};

