/* =========================================================
   STATUS
========================================================= */

export const updateVendorStatus = async (
  req: AuthRequest,
  res: Response
) => {
  try {
    const organizationId =
      getOrganizationId(req);

    const id =
      getParam(
        req.params?.id
      ).trim();

    const status =
      typeof req.body?.status ===
      "string"
        ? req.body.status
            .trim()
            .toUpperCase()
        : "";

    if (!organizationId) {
      return res.status(401).json({
        success: false,
        message:
          "Organization context is required.",
      });
    }

    if (!id) {
      return res.status(400).json({
        success: false,
        message: "Vendor ID is required.",
      });
    }

    if (
      status !== "ACTIVE" &&
      status !== "INACTIVE"
    ) {
      return res.status(400).json({
        success: false,
        message:
          "Vendor status must be ACTIVE or INACTIVE.",
      });
    }

    const existing =
      await prisma.vendor.findFirst({
        where: {
          id,
          organizationId,
        },
      });

    if (!existing) {
      return res.status(404).json({
        success: false,
        message: "Vendor not found.",
      });
    }

    const vendor =
      await prisma.vendor.update({
        where: {
          id,
        },
        data: {
          status,
        },
      });

    return res.status(200).json({
      success: true,
      message:
        status === "ACTIVE"
          ? "Vendor activated successfully."
          : "Vendor deactivated successfully.",
      vendor,
    });
  } catch (error) {
    console.error(
      "UPDATE VENDOR STATUS ERROR:",
      error
    );

    return res.status(500).json({
      success: false,
      message:
        "Failed to update vendor status.",
    });
  }
};

/* =========================================================
   DELETE
========================================================= */

export const deleteVendor = async (
  req: AuthRequest,
  res: Response
) => {
  try {
    const organizationId =
      getOrganizationId(req);

    const id =
      getParam(
        req.params?.id
      ).trim();

    if (!organizationId) {
      return res.status(401).json({
        success: false,
        message:
          "Organization context is required.",
      });
    }

    if (!id) {
      return res.status(400).json({
        success: false,
        message: "Vendor ID is required.",
      });
    }

    const vendor =
      await prisma.vendor.findFirst({
        where: {
          id,
          organizationId,
        },
        include: {
          _count: {
            select: {
              payables: true,
              expenses: true,
              procurementRequests: true,
            },
          },
        },
      });

    if (!vendor) {
      return res.status(404).json({
        success: false,
        message: "Vendor not found.",
      });
    }

    if (
      vendor._count.payables > 0 ||
      vendor._count.expenses > 0 ||
      vendor._count
        .procurementRequests > 0
    ) {
      return res.status(409).json({
        success: false,
        message:
          "This vendor has financial or procurement records and cannot be deleted. Deactivate the vendor instead.",
      });
    }

    await prisma.vendor.delete({
      where: {
        id,
      },
    });

    return res.status(200).json({
      success: true,
      message:
        "Vendor deleted successfully.",
    });
  } catch (error) {
    console.error(
      "DELETE VENDOR ERROR:",
      error
    );

    return res.status(500).json({
      success: false,
      message: "Failed to delete vendor.",
    });
  }
};
