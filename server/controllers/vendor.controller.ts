import { Response } from "express";
import prisma from "../config/prisma";
import { AuthRequest } from "../middleware/auth.middleware";

const getParam = (value: unknown): string => {
  if (Array.isArray(value)) {
    const first = value[0];

    if (typeof first === "string") {
      return first;
    }

    return "";
  }

  return typeof value === "string" ? value : "";
};

const cleanOptionalString = (
  value: unknown
): string | null => {
  if (typeof value !== "string") {
    return null;
  }

  const cleaned = value.trim();

  return cleaned || null;
};

const getOrganizationId = (
  req: AuthRequest
): string | null => {
  const organizationId =
    req.user?.organizationId?.trim();

  return organizationId || null;
};

/* =========================================================
   PAGINATION
========================================================= */

const DEFAULT_PAGE = 1;
const DEFAULT_LIMIT = 25;
const MAX_LIMIT = 100;

const ALLOWED_LIMITS = [10, 25, 50, 100] as const;

type VendorSortField =
  | "createdAt"
  | "updatedAt"
  | "name"
  | "vendorCode"
  | "status";

type SortOrder = "asc" | "desc";

const parsePositiveInteger = (
  value: unknown,
  fallback: number
): number => {
  const parsed = Number.parseInt(
    String(value ?? ""),
    10
  );

  if (!Number.isFinite(parsed) || parsed < 1) {
    return fallback;
  }

  return parsed;
};

const parseLimit = (
  value: unknown
): number => {
  const parsed = Number.parseInt(
    String(value ?? ""),
    10
  );

  if (
    !Number.isFinite(parsed) ||
    parsed < 1
  ) {
    return DEFAULT_LIMIT;
  }

  if (ALLOWED_LIMITS.includes(
    parsed as (typeof ALLOWED_LIMITS)[number]
  )) {
    return parsed;
  }

  return Math.min(parsed, MAX_LIMIT);
};

const parseSortField = (
  value: unknown
): VendorSortField => {
  const field = getParam(value);

  if (
    field === "name" ||
    field === "vendorCode" ||
    field === "status" ||
    field === "updatedAt"
  ) {
    return field;
  }

  return "createdAt";
};

const parseSortOrder = (
  value: unknown
): SortOrder => {
  return getParam(value).toLowerCase() === "asc"
    ? "asc"
    : "desc";
};

/* =========================================================
   VENDOR CODE
========================================================= */

/**
 * Generate the next vendor code for one organization.
 *
 * Codes are generated by the server and are never accepted
 * from the client.
 */
const generateVendorCode = async (
  organizationId: string
): Promise<string> => {
  const year = new Date().getFullYear();
  const prefix = `VEN-${year}-`;

  const existing =
    await prisma.vendor.findMany({
      where: {
        organizationId,
        vendorCode: {
          startsWith: prefix,
        },
      },
      select: {
        vendorCode: true,
      },
      orderBy: {
        vendorCode: "desc",
      },
    });

  let highest = 0;

  for (const item of existing) {
    const match = item.vendorCode.match(
      new RegExp(`^VEN-${year}-(\\d+)$`)
    );

    if (match) {
      highest = Math.max(
        highest,
        Number(match[1])
      );
    }
  }

  return `${prefix}${String(
    highest + 1
  ).padStart(3, "0")}`;
};

/* =========================================================
   CREATE
========================================================= */

export const createVendor = async (
  req: AuthRequest,
  res: Response
) => {
  try {
    const organizationId =
      getOrganizationId(req);

    if (!organizationId) {
      return res.status(401).json({
        success: false,
        message:
          "Organization context is required.",
      });
    }

    const {
      name,
      email,
      phoneNumber,
      address,
      taxNumber,
    } = req.body ?? {};

    if (
      typeof name !== "string" ||
      !name.trim()
    ) {
      return res.status(400).json({
        success: false,
        message: "Vendor name is required.",
      });
    }

    for (
      let attempt = 0;
      attempt < 5;
      attempt++
    ) {
      try {
        const vendorCode =
          await generateVendorCode(
            organizationId
          );

        const vendor =
          await prisma.vendor.create({
            data: {
              organizationId,
              vendorCode,
              name: name.trim(),
              email:
                typeof email === "string" &&
                email.trim()
                  ? email
                      .trim()
                      .toLowerCase()
                  : null,
              phoneNumber:
                cleanOptionalString(
                  phoneNumber
                ),
              address:
                cleanOptionalString(
                  address
                ),
              taxNumber:
                typeof taxNumber ===
                  "string" &&
                taxNumber.trim()
                  ? taxNumber
                      .trim()
                      .toUpperCase()
                  : null,
              status: "ACTIVE",
            },
          });

        return res.status(201).json({
          success: true,
          message:
            "Vendor created successfully.",
          vendor,
        });
      } catch (error: any) {
        if (error?.code === "P2002") {
          continue;
        }

        throw error;
      }
    }

    return res.status(409).json({
      success: false,
      message:
        "Unable to generate a unique vendor code. Please try again.",
    });
  } catch (error) {
    console.error(
      "CREATE VENDOR ERROR:",
      error
    );

    return res.status(500).json({
      success: false,
      message: "Failed to create vendor.",
    });
  }
};

/* =========================================================
   GET ALL — PAGINATED
========================================================= */

export const getVendors = async (
  req: AuthRequest,
  res: Response
) => {
  try {
    const organizationId =
      getOrganizationId(req);

    if (!organizationId) {
      return res.status(401).json({
        success: false,
        message:
          "Organization context is required.",
      });
    }

    const requestedPage =
      parsePositiveInteger(
        req.query?.page,
        DEFAULT_PAGE
      );

    const limit = parseLimit(
      req.query?.limit
    );

    const search = getParam(
      req.query?.search
    ).trim();

    const requestedStatus =
      getParam(
        req.query?.status
      )
        .trim()
        .toUpperCase();

    const status =
      requestedStatus === "ACTIVE" ||
      requestedStatus === "INACTIVE"
        ? requestedStatus
        : undefined;

    const sortBy =
      parseSortField(
        req.query?.sortBy
      );

    const sortOrder =
      parseSortOrder(
        req.query?.sortOrder
      );

    const where: any = {
      organizationId,
    };

    if (status) {
      where.status = status;
    }

    if (search) {
      where.OR = [
        {
          vendorCode: {
            contains: search,
            mode: "insensitive",
          },
        },
        {
          name: {
            contains: search,
            mode: "insensitive",
          },
        },
        {
          email: {
            contains: search,
            mode: "insensitive",
          },
        },
        {
          phoneNumber: {
            contains: search,
            mode: "insensitive",
          },
        },
        {
          address: {
            contains: search,
            mode: "insensitive",
          },
        },
        {
          taxNumber: {
            contains: search,
            mode: "insensitive",
          },
        },
      ];
    }

    const skip =
      (requestedPage - 1) * limit;

    const orderBy = {
      [sortBy]: sortOrder,
    } as Record<
      VendorSortField,
      SortOrder
    >;

    const [
      vendors,
      total,
      active,
      inactive,
    ] = await Promise.all([
      prisma.vendor.findMany({
        where,
        skip,
        take: limit,
        orderBy: [
          orderBy,
          {
            id: "desc",
          },
        ],
      }),

      prisma.vendor.count({
        where,
      }),

      prisma.vendor.count({
        where: {
          organizationId,
          status: "ACTIVE",
        },
      }),

      prisma.vendor.count({
        where: {
          organizationId,
          status: "INACTIVE",
        },
      }),
    ]);

    const totalPages =
      total === 0
        ? 0
        : Math.ceil(total / limit);

    const page =
      totalPages === 0
        ? 1
        : Math.min(
            requestedPage,
            totalPages
          );

    /*
     * If the requested page is beyond the
     * available range, fetch the corrected
     * page rather than returning an empty page.
     */
    let finalVendors = vendors;

    if (
      requestedPage !== page
    ) {
      finalVendors =
        await prisma.vendor.findMany({
          where,
          skip: (page - 1) * limit,
          take: limit,
          orderBy: [
            orderBy,
            {
              id: "desc",
            },
          ],
        });
    }

    return res.status(200).json({
      success: true,
      vendors: finalVendors,
      count: total,
      pagination: {
        page,
        limit,
        total,
        totalPages,
        hasPreviousPage: page > 1,
        hasNextPage:
          totalPages > 0 &&
          page < totalPages,
      },
      summary: {
        total,
        active,
        inactive,
      },
      filters: {
        search,
        status: status ?? "ALL",
        sortBy,
        sortOrder,
      },
    });
  } catch (error) {
    console.error(
      "GET VENDORS ERROR:",
      error
    );

    return res.status(500).json({
      success: false,
      message: "Failed to fetch vendors.",
    });
  }
};

