/* =========================================================
   CREATE PROCUREMENT REQUEST
========================================================= */

export const createProcurementRequest =
  async (
    req: AuthRequest,
    res: Response
  ) => {
    try {
      const organizationId =
        getOrganizationId(req);

      const userId =
        getUserId(req);

      if (!organizationId) {
        return res.status(401).json({
          success: false,
          code: "ORGANIZATION_CONTEXT_REQUIRED",
          message:
            "Organization context is required.",
        });
      }

      if (!userId) {
        return res.status(401).json({
          success: false,
          code: "USER_CONTEXT_REQUIRED",
          message:
            "Authenticated user context is required.",
        });
      }

      const item =
        normalizeItem(req.body?.item);

      const department =
        normalizeDepartment(
          req.body?.department
        );

      const quantity =
        typeof req.body?.quantity === "number"
          ? req.body.quantity
          : Number(req.body?.quantity);

      const estimatedAmount =
        typeof req.body?.estimatedAmount === "number"
          ? req.body.estimatedAmount
          : Number(req.body?.estimatedAmount);

      const notes =
        cleanOptionalString(
          req.body?.notes
        );

      const vendorId =
        typeof req.body?.vendorId === "string" &&
        req.body.vendorId.trim()
          ? req.body.vendorId.trim()
          : null;

      /* =====================================================
         VALIDATION
      ===================================================== */

      if (!item) {
        return res.status(400).json({
          success: false,
          code: "ITEM_REQUIRED",
          message:
            "Item or description is required.",
        });
      }

      if (item.length > 500) {
        return res.status(400).json({
          success: false,
          code: "ITEM_TOO_LONG",
          message:
            "Item or description must not exceed 500 characters.",
        });
      }

      if (!department) {
        return res.status(400).json({
          success: false,
          code: "DEPARTMENT_REQUIRED",
          message:
            "Department is required.",
        });
      }

      if (department.length > 100) {
        return res.status(400).json({
          success: false,
          code: "DEPARTMENT_TOO_LONG",
          message:
            "Department must not exceed 100 characters.",
        });
      }

      if (
        !Number.isInteger(quantity) ||
        quantity < 1 ||
        quantity > 1000000
      ) {
        return res.status(400).json({
          success: false,
          code: "INVALID_QUANTITY",
          message:
            "Quantity must be a whole number greater than zero.",
        });
      }

      if (
        !Number.isFinite(estimatedAmount) ||
        estimatedAmount <= 0 ||
        estimatedAmount > 100000000000
      ) {
        return res.status(400).json({
          success: false,
          code: "INVALID_ESTIMATED_AMOUNT",
          message:
            "Estimated amount must be greater than zero and within the allowed limit.",
        });
      }

      if (
        notes &&
        notes.length > 2000
      ) {
        return res.status(400).json({
          success: false,
          code: "NOTES_TOO_LONG",
          message:
            "Notes must not exceed 2000 characters.",
        });
      }

      /* =====================================================
         TENANT-SAFE VENDOR VALIDATION
      ===================================================== */

      if (vendorId) {
        const vendor =
          await validateVendor(
            organizationId,
            vendorId
          );

        if (!vendor) {
          return res.status(400).json({
            success: false,
            code: "INVALID_VENDOR",
            message:
              "Selected vendor was not found in this organization or is inactive.",
          });
        }
      }

      /*
       * Request creation is an operational event.
       *
       * IMPORTANT:
       * No AP, Expense, Asset, Payment or GL transaction is
       * created here.
       *
       * Those modules should post only when their own
       * financial event occurs.
       */

      for (let attempt = 0; attempt < 5; attempt += 1) {
        const requestCode =
          await generateRequestCode(
            organizationId
          );

        try {
          const request =
            await prisma.procurementRequest.create({
              data: {
                organizationId,
                requestedBy: userId,
                requestCode,
                item,
                department,
                quantity,
                estimatedAmount,
                notes,
                vendorId,
                status: "PENDING",
              },
              include: {
                vendor: {
                  select: {
                    id: true,
                    vendorCode: true,
                    name: true,
                    email: true,
                    phoneNumber: true,
                    status: true,
                  },
                },
              },
            });

          return res.status(201).json({
            success: true,
            message:
              "Procurement request created successfully.",
            request,
          });
        } catch (createError: unknown) {
          /*
           * Concurrent submissions may calculate the same
           * next number. The database unique constraint is
           * authoritative; retry with a newly generated code.
           */
          if (
            isUniqueViolation(
              createError
            ) &&
            attempt < 4
          ) {
            continue;
          }

          throw createError;
        }
      }

      return res.status(409).json({
        success: false,
        code: "REQUEST_CODE_GENERATION_FAILED",
        message:
          "Could not generate a unique procurement request code. Please try again.",
      });
    } catch (error) {
      console.error(
        "CREATE PROCUREMENT REQUEST ERROR:",
        error
      );

      return res.status(500).json({
        success: false,
        code: "PROCUREMENT_CREATE_FAILED",
        message:
          "Failed to create procurement request.",
      });
    }
  };

/* =========================================================
   UPDATE PROCUREMENT REQUEST
========================================================= */


export const submitProcurementRequest = async (
  req: AuthRequest,
  res: Response
) => {
  try {
    const organizationId = getOrganizationId(req);
    const userId = req.user?.userId ?? null;
    const id = getParam(req.params.id);

    if (!organizationId) {
      return res.status(401).json({
        message: "Organization context is required",
      });
    }

    if (!userId) {
      return res.status(401).json({
        message: "Authenticated user is required",
      });
    }

    const result = await prisma.$transaction(async (tx) => {
      const request = await tx.procurementRequest.findFirst({
        where: {
          id,
          organizationId,
        },
        include: {
          vendor: true,
          approval: true,
          budget: true,
        },
      });

      if (!request) {
        throw new Error("PROCUREMENT_REQUEST_NOT_FOUND");
      }

      if (request.status !== "PENDING") {
        throw new Error("PROCUREMENT_REQUEST_ALREADY_SUBMITTED");
      }

      const year = request.createdAt.getFullYear();

      const budget = await tx.budget.findFirst({
        where: {
          organizationId,
          department: request.department,
          year,
        },
      });

      if (!budget) {
        throw new Error("PROCUREMENT_BUDGET_NOT_FOUND");
      }

      const committed = await tx.procurementRequest.aggregate({
        where: {
          organizationId,
          department: request.department,
          status: {
            in: ["APPROVED", "ORDERED", "DELIVERED"],
          },
          id: {
            not: request.id,
          },
        },
        _sum: {
          estimatedAmount: true,
        },
      });

      const committedAmount = committed._sum.estimatedAmount ?? 0;
      const availableAmount = budget.amount - committedAmount;

      if (request.estimatedAmount > availableAmount) {
        throw new Error("PROCUREMENT_BUDGET_EXCEEDED");
      }

      const approval = await tx.approval.create({
        data: {
          module: "PROCUREMENT",
          description: `Procurement request ${request.requestCode} - ${request.item}`,
          amount: request.estimatedAmount,
          requestedBy: userId,
          status: "PENDING",
          organizationId,
        },
      });

      const updatedRequest = await tx.procurementRequest.update({
        where: {
          id: request.id,
        },
        data: {
          approvalId: approval.id,
          budgetId: budget.id,
        },
        include: {
          vendor: true,
          approval: true,
          budget: true,
        },
      });

      await tx.auditTrail.create({
        data: {
          user: userId,
          action: "SUBMITTED_FOR_APPROVAL",
          module: "PROCUREMENT",
          details: JSON.stringify({
            procurementRequestId: request.id,
            requestCode: request.requestCode,
            approvalId: approval.id,
            budgetId: budget.id,
            amount: request.estimatedAmount,
          }),
          organizationId,
        },
      });

      return updatedRequest;
    });

    return res.status(200).json(result);
  } catch (error) {
    console.error("Submit procurement request error:", error);

    const message =
      error instanceof Error ? error.message : "Unknown error";

    if (message === "PROCUREMENT_REQUEST_NOT_FOUND") {
      return res.status(404).json({
        message: "Procurement request not found",
      });
    }

    if (message === "PROCUREMENT_REQUEST_ALREADY_SUBMITTED") {
      return res.status(400).json({
        message: "Procurement request has already been submitted",
      });
    }

    if (message === "PROCUREMENT_BUDGET_NOT_FOUND") {
      return res.status(400).json({
        message:
          "No matching budget was found for this department and financial year",
      });
    }

    if (message === "PROCUREMENT_BUDGET_EXCEEDED") {
      return res.status(400).json({
        message:
          "Procurement request exceeds the available departmental budget",
      });
    }

    return res.status(500).json({
      message: "Failed to submit procurement request",
    });
  }
};
