import { Response } from "express";
import prisma from "../config/prisma";
import { AuthRequest } from "../middleware/auth.middleware";

const getParam = (
  value: string | string[] | undefined
): string => {
  if (Array.isArray(value)) return value[0] ?? "";
  return value ?? "";
};

const getOrganizationId = (
  req: AuthRequest
): string | null => {
  const organizationId = req.user?.organizationId?.trim();
  return organizationId || null;
};

const getUserId = (
  req: AuthRequest
): string | null => {
  const userId = req.user?.userId?.trim();
  return userId || null;
};

const cleanOptionalString = (
  value: unknown
): string | null => {
  if (typeof value !== "string") return null;
  const cleaned = value.trim();
  return cleaned || null;
};

const normalizeDepartment = (
  value: unknown
): string => {
  if (typeof value !== "string") return "";
  return value.trim();
};

const normalizeItem = (
  value: unknown
): string => {
  if (typeof value !== "string") return "";
  return value.trim();
};

/*
 * Procurement request numbers are generated by the server.
 *
 * Format:
 * PR-YYYY-NNN
 *
 * The sequence is tenant scoped because every lookup includes
 * organizationId.
 */
const generateRequestCode = async (
  organizationId: string
): Promise<string> => {
  const year = new Date().getFullYear();
  const prefix = `PR-${year}-`;

  const latest = await prisma.procurementRequest.findFirst({
    where: {
      organizationId,
      requestCode: {
        startsWith: prefix,
      },
    },
    orderBy: {
      requestCode: "desc",
    },
    select: {
      requestCode: true,
    },
  });

  let nextNumber = 1;

  if (latest?.requestCode) {
    const match = latest.requestCode.match(
      /^PR-\d{4}-(\d+)$/
    );

    if (match) {
      const currentNumber = Number(match[1]);

      if (Number.isFinite(currentNumber)) {
        nextNumber = currentNumber + 1;
      }
    }
  }

  return `${prefix}${String(nextNumber).padStart(3, "0")}`;
};

const isUniqueViolation = (
  error: unknown
): boolean => {
  return (
    typeof error === "object" &&
    error !== null &&
    "code" in error &&
    (error as { code?: unknown }).code === "P2002"
  );
};

const validateVendor = async (
  organizationId: string,
  vendorId: string | null
) => {
  if (!vendorId) return null;

  return prisma.vendor.findFirst({
    where: {
      id: vendorId,
      organizationId,
      status: "ACTIVE",
    },
    select: {
      id: true,
      vendorCode: true,
      name: true,
      email: true,
      phoneNumber: true,
      status: true,
    },
  });
};

/* =========================================================
   GET ALL PROCUREMENT REQUESTS

   Server-side pagination and filtering are used here so the
   browser never needs to load the entire tenant dataset.
========================================================= */

export const getProcurementRequests =
  async (
    req: AuthRequest,
    res: Response
  ) => {
    try {
      const organizationId =
        getOrganizationId(req);

      if (!organizationId) {
        return res.status(401).json({
          success: false,
          code: "ORGANIZATION_CONTEXT_REQUIRED",
          message:
            "Organization context is required.",
        });
      }

      const rawPage = Number(req.query.page ?? 1);
      const rawPageSize = Number(req.query.pageSize ?? 10);
      const search =
        typeof req.query.search === "string"
          ? req.query.search.trim()
          : "";
      const status =
        typeof req.query.status === "string"
          ? req.query.status.trim().toUpperCase()
          : "ALL";
      const department =
        typeof req.query.department === "string"
          ? req.query.department.trim()
          : "";

      const page =
        Number.isInteger(rawPage) && rawPage > 0
          ? rawPage
          : 1;

      const allowedPageSizes = [10, 25, 50];
      const pageSize = allowedPageSizes.includes(
        rawPageSize
      )
        ? rawPageSize
        : 10;

      const allowedStatuses = [
        "PENDING",
        "APPROVED",
        "ORDERED",
        "DELIVERED",
        "REJECTED",
      ] as const;

      if (
        status !== "ALL" &&
        !allowedStatuses.includes(
          status as (typeof allowedStatuses)[number]
        )
      ) {
        return res.status(400).json({
          success: false,
          code: "INVALID_PROCUREMENT_STATUS",
          message: "Invalid procurement status filter.",
        });
      }

      type ProcurementStatus =
        (typeof allowedStatuses)[number];

      const where: {
        organizationId: string;
        status?: ProcurementStatus;
        department?: string;
        OR?: Array<Record<string, unknown>>;
      } = {
        organizationId,
      };

      if (status !== "ALL") {
        where.status =
          status as ProcurementStatus;
      }

      if (department) {
        where.department = department;
      }

      if (search) {
        where.OR = [
          {
            requestCode: {
              contains: search,
              mode: "insensitive",
            },
          },
          {
            item: {
              contains: search,
              mode: "insensitive",
            },
          },
          {
            department: {
              contains: search,
              mode: "insensitive",
            },
          },
          {
            requestedBy: {
              contains: search,
              mode: "insensitive",
            },
          },
          {
            vendor: {
              is: {
                name: {
                  contains: search,
                  mode: "insensitive",
                },
              },
            },
          },
          {
            vendor: {
              is: {
                vendorCode: {
                  contains: search,
                  mode: "insensitive",
                },
              },
            },
          },
        ];
      }

      const skip = (page - 1) * pageSize;

      const [
        total,
        requests,
        allCount,
        pending,
        approved,
        ordered,
        estimatedSpend,
      ] = await prisma.$transaction([
        prisma.procurementRequest.count({
          where,
        }),

        prisma.procurementRequest.findMany({
          where,
          include: {
            vendor: {
              select: {
                id: true,
                vendorCode: true,
                name: true,
                email: true,
                phoneNumber: true,
                status: true,
              },
            },
          },
          orderBy: {
            createdAt: "desc",
          },
          skip,
          take: pageSize,
        }),

        prisma.procurementRequest.count({
          where: { organizationId },
        }),

        prisma.procurementRequest.count({
          where: {
            organizationId,
            status: "PENDING",
          },
        }),

        prisma.procurementRequest.count({
          where: {
            organizationId,
            status: "APPROVED",
          },
        }),

        prisma.procurementRequest.count({
          where: {
            organizationId,
            status: "ORDERED",
          },
        }),

        prisma.procurementRequest.aggregate({
          where: { organizationId },
          _sum: {
            estimatedAmount: true,
          },
        }),
      ]);

      const totalPages =
        total === 0
          ? 0
          : Math.ceil(total / pageSize);

      const safePage =
        totalPages > 0
          ? Math.min(page, totalPages)
          : 1;

      return res.status(200).json({
        success: true,
        count: requests.length,
        requests,
        pagination: {
          page: safePage,
          pageSize,
          total,
          totalPages,
        },
        summary: {
          totalRequests: allCount,
          estimatedSpend:
            Number(
              estimatedSpend._sum.estimatedAmount ?? 0
            ),
          pending,
          approved,
          ordered,
        },
      });
    } catch (error) {
      console.error(
        "GET PROCUREMENT REQUESTS ERROR:",
        error
      );

      return res.status(500).json({
        success: false,
        code: "PROCUREMENT_FETCH_FAILED",
        message:
          "Failed to fetch procurement requests.",
      });
    }
  };

